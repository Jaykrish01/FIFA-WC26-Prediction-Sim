VERY_NICHE_EXCLUDE = {
    "International Tournament of Peoples, Cultures and Tribes",
    "The Other Final",
    "Viva World Cup",
    "World Unity Cup",
    "TIFOCO Tournament",
    "SKN Football Festival",
    "Scania 100 Tournament",
    "Niamh Challenge Cup",
    "Real Madrid 75th Anniversary Cup",
    "Tynwald Hill Tournament",
}

def get_tournament_weight(name: str) -> float:
    if not isinstance(name, str):
        return 0.0

    name = name.strip()

    if name in VERY_NICHE_EXCLUDE:
        return 0.0

    if name in MAJOR_TOURNAMENTS:
        return MAJOR_TOURNAMENTS[name]

    if name in QUALIFICATION_TOURNAMENTS:
        return QUALIFICATION_TOURNAMENTS[name]

    if name in REGIONAL_COMPETITIVE:
        return REGIONAL_COMPETITIVE[name]

    # fallback rules
    if "friendly" in name.lower():
        return 0.70

    if "qualification" in name.lower() or "qualifier" in name.lower():
        return 1.20

    # anything unknown gets a very small weight
    return 0.35
